-- Run in the target PostgreSQL database.
CREATE TABLE IF NOT EXISTS product_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT NOT NULL DEFAULT 0,
    category_code VARCHAR(64) NOT NULL,
    category_name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    icon_url VARCHAR(500),
    sort_order INTEGER NOT NULL DEFAULT 0,
    status SMALLINT NOT NULL DEFAULT 1 CHECK (status IN (0, 1)),
    is_deleted SMALLINT NOT NULL DEFAULT 0 CHECK (is_deleted IN (0, 1)),
    created_by BIGINT,
    updated_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_product_category_code UNIQUE (category_code),
    CONSTRAINT ck_product_category_parent CHECK (parent_id >= 0)
);

CREATE INDEX IF NOT EXISTS idx_product_category_parent ON product_category (parent_id);
CREATE INDEX IF NOT EXISTS idx_product_category_status ON product_category (status, is_deleted);
CREATE INDEX IF NOT EXISTS idx_product_category_sort ON product_category (parent_id, sort_order, id);

CREATE OR REPLACE FUNCTION set_product_category_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_product_category_updated_at ON product_category;
CREATE TRIGGER trg_product_category_updated_at
BEFORE UPDATE ON product_category
FOR EACH ROW EXECUTE FUNCTION set_product_category_updated_at();

COMMENT ON TABLE product_category IS 'IoT product categories';
COMMENT ON COLUMN product_category.parent_id IS 'Parent category ID; 0 means root category';
COMMENT ON COLUMN product_category.status IS '1 enabled, 0 disabled';
COMMENT ON COLUMN product_category.is_deleted IS '1 deleted, 0 active';

CREATE TABLE IF NOT EXISTS iot_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(100),
    role SMALLINT NOT NULL DEFAULT 0 CHECK (role IN (0, 1)),
    status SMALLINT NOT NULL DEFAULT 1 CHECK (status IN (0, 1)),
    email_verified_at TIMESTAMP WITH TIME ZONE,
    password_changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_iot_user_email CHECK (email = BTRIM(email) AND email <> ''),
    CONSTRAINT ck_iot_user_password_hash CHECK (password_hash <> '')
);

ALTER TABLE iot_user ADD COLUMN IF NOT EXISTS role SMALLINT NOT NULL DEFAULT 0
    CHECK (role IN (0, 1));

CREATE UNIQUE INDEX IF NOT EXISTS uk_iot_user_email_ci ON iot_user (LOWER(email));

CREATE OR REPLACE FUNCTION set_iot_user_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_iot_user_updated_at ON iot_user;
CREATE TRIGGER trg_iot_user_updated_at
BEFORE UPDATE ON iot_user
FOR EACH ROW EXECUTE FUNCTION set_iot_user_updated_at();

COMMENT ON TABLE iot_user IS 'Web cloud platform accounts';
COMMENT ON COLUMN iot_user.email IS 'Registration and login identifier; unique ignoring case';
COMMENT ON COLUMN iot_user.password_hash IS 'Encoded adaptive password hash; never store plaintext passwords';
COMMENT ON COLUMN iot_user.role IS '0 user, 1 administrator; registration always creates a user';
COMMENT ON COLUMN iot_user.status IS '1 enabled, 0 disabled';
COMMENT ON COLUMN iot_user.email_verified_at IS 'NULL until the email address is verified';
