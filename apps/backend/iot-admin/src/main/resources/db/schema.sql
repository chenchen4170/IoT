-- Run in the target PostgreSQL database.
CREATE TABLE IF NOT EXISTS product_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT NOT NULL DEFAULT 0,
    category_code VARCHAR(64) NOT NULL,
    category_name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    icon_url VARCHAR(500),
    sort_order INTEGER NOT NULL DEFAULT 0,
    status SMALLINT NOT NULL DEFAULT 1 CHECK (status IN (0, 1)),
    is_deleted SMALLINT NOT NULL DEFAULT 0 CHECK (is_deleted IN (0, 1)),
    created_by BIGINT,
    updated_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_product_category_code UNIQUE (category_code),
    CONSTRAINT ck_product_category_parent CHECK (parent_id >= 0)
);

CREATE INDEX IF NOT EXISTS idx_product_category_parent ON product_category (parent_id);
CREATE INDEX IF NOT EXISTS idx_product_category_status ON product_category (status, is_deleted);
CREATE INDEX IF NOT EXISTS idx_product_category_sort ON product_category (parent_id, sort_order, id);

CREATE OR REPLACE FUNCTION set_product_category_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_product_category_updated_at ON product_category;
CREATE TRIGGER trg_product_category_updated_at
BEFORE UPDATE ON product_category
FOR EACH ROW EXECUTE FUNCTION set_product_category_updated_at();

COMMENT ON TABLE product_category IS 'IoT product categories';
COMMENT ON COLUMN product_category.parent_id IS 'Parent category ID; 0 means root category';
COMMENT ON COLUMN product_category.status IS '1 enabled, 0 disabled';
COMMENT ON COLUMN product_category.is_deleted IS '1 deleted, 0 active';
